/**
 * file: js/mgdb-download.js
 *
 * purpose: Scrollspy and clipboard copy helpers for Bulk Downloads & Globus Data Portal
 */

(function () {
  'use strict';

  function init() {
    initScrollSpy();
    initFileFinder();
  }

  /* ------------------------------------------------------------------
     Guided genome file finder

     Driven entirely by data/download_catalog.json, which is generated by
     tools/gen_download_catalog.py from the genome download directory. The
     whole catalog is one request because it is served compressed \(~1 MB of
     JSON, ~60 KB on the wire\), which buys instant assembly switching with
     no further round trips.
     ------------------------------------------------------------------ */

  var ROLE_NAMES = {
    all: 'All types',
    assembly: 'Genome assembly',
    gene_annotation: 'Gene annotation',
    protein: 'Proteins',
    cds: 'CDS',
    transcript: 'Transcripts',
    gene_sequence: 'Gene sequences',
    transposable_elements: 'TE annotation',
    special_annotation: 'Specialized annotation',
    cross_reference: 'Cross references',
    metadata: 'Metadata',
    checksum: 'Checksums',
    documentation: 'README',
    table: 'Tables',
    index: 'Indexes',
    other: 'Other files'
  };

  var ROLE_ORDER = ['all', 'assembly', 'gene_annotation', 'protein', 'cds',
    'transcript', 'gene_sequence', 'transposable_elements', 'special_annotation',
    'cross_reference', 'metadata', 'documentation', 'checksum', 'table', 'index', 'other'];

  var ROLE_ABBR = {
    assembly: 'DNA',
    gene_annotation: 'GFF',
    protein: 'AA',
    cds: 'CDS',
    transcript: 'RNA',
    gene_sequence: 'GENE',
    transposable_elements: 'TE',
    special_annotation: 'ANN',
    cross_reference: 'XREF',
    metadata: 'META',
    checksum: 'MD5',
    documentation: 'DOC',
    table: 'TSV',
    index: 'IDX'
  };

  function initFileFinder() {
    var root = document.getElementById('downloads-finder');
    if (!root || !window.fetch) return;

    var el = {
      loading: document.getElementById('download-explorer-loading'),
      error: document.getElementById('download-explorer-error'),
      app: document.getElementById('download-explorer-app'),
      search: document.getElementById('download-assembly-search'),
      clear: document.getElementById('download-assembly-clear'),
      status: document.getElementById('download-assembly-status'),
      results: document.getElementById('download-assembly-results'),
      name: document.getElementById('download-selected-name'),
      meta: document.getElementById('download-selected-meta'),
      directory: document.getElementById('download-open-directory'),
      copyCore: document.getElementById('download-copy-core'),
      roles: document.getElementById('download-role-filters'),
      recommended: document.getElementById('download-recommended-only'),
      summary: document.getElementById('download-file-summary'),
      files: document.getElementById('download-file-results'),
      guide: document.getElementById('download-command-guide'),
      guideFile: document.getElementById('download-command-file'),
      guideClose: document.getElementById('download-command-close')
    };

    var catalog = null;
    var assembly = null;
    var role = 'all';
    var commands = null;

    /* Copies a raw string. Distinct from the page's window.copyText, which
       takes the id of an element to read. */
    function copyValue(text, button) {
      function done() {
        if (!button) return;
        var original = button.textContent;
        button.textContent = 'Copied';
        window.setTimeout(function () { button.textContent = original; }, 1400);
      }
      if (navigator.clipboard && navigator.clipboard.writeText) {
        navigator.clipboard.writeText(text).then(done);
        return;
      }
      var helper = document.createElement('textarea');
      helper.value = text;
      helper.setAttribute('readonly', 'readonly');
      helper.style.position = 'fixed';
      helper.style.opacity = '0';
      document.body.appendChild(helper);
      helper.select();
      document.execCommand('copy');
      document.body.removeChild(helper);
      done();
    }

    function searchText(entry) {
      return [entry.name, entry.id, entry.species, entry.project, entry.status, entry.version]
        .join(' ').toLowerCase();
    }

    /* B73 first, then the other NAM founders, then everything alphabetically:
       the reference genome is what most people arrive wanting. */
    function rank(entry) {
      if (entry.id === 'Zm-B73-REFERENCE-NAM-5.0') return 0;
      if (entry.id === 'Zm-B73-REFERENCE-GRAMENE-4.0') return 1;
      if (entry.id === 'B73_RefGen_v3') return 2;
      if (String(entry.project).toLowerCase() === 'nam') return 10;
      return 20;
    }

    function renderAssemblies() {
      var query = el.search.value.trim().toLowerCase();
      var matches = catalog.assemblies.filter(function (entry) {
        return !query || searchText(entry).indexOf(query) !== -1;
      });

      matches.sort(function (a, b) {
        return (rank(a) - rank(b)) || a.name.localeCompare(b.name) || a.id.localeCompare(b.id);
      });

      var shown = matches.slice(0, query ? 40 : 20);
      el.results.innerHTML = '';

      shown.forEach(function (entry) {
        var button = document.createElement('button');
        button.type = 'button';
        button.className = 'finder-assembly-option';
        button.setAttribute('role', 'option');
        var selected = assembly && assembly.id === entry.id;
        button.setAttribute('aria-selected', selected ? 'true' : 'false');
        if (selected) button.classList.add('is-selected');

        var title = document.createElement('strong');
        title.textContent = entry.name;
        var release = document.createElement('span');
        release.textContent = entry.status + ' ' + entry.version;
        var detail = document.createElement('small');
        detail.textContent = entry.species + ' · ' + entry.file_count + ' files';

        button.appendChild(title);
        button.appendChild(release);
        button.appendChild(detail);
        button.addEventListener('click', function () { selectAssembly(entry); });
        el.results.appendChild(button);
      });

      if (!matches.length) {
        var empty = document.createElement('p');
        empty.className = 'finder-assembly-empty';
        empty.textContent = 'No assemblies match that search.';
        el.results.appendChild(empty);
      }

      el.status.textContent = matches.length > shown.length
        ? 'Showing ' + shown.length + ' of ' + matches.length + ' matches. Type more to narrow the list.'
        : matches.length + (matches.length === 1 ? ' assembly found.' : ' assemblies found.');
      el.clear.hidden = !query;
    }

    function renderRoles() {
      var counts = { all: assembly.files.length };
      assembly.files.forEach(function (file) {
        counts[file.role] = (counts[file.role] || 0) + 1;
      });

      el.roles.innerHTML = '';
      ROLE_ORDER.forEach(function (name) {
        if (!counts[name]) return;
        var button = document.createElement('button');
        button.type = 'button';
        button.className = 'finder-role-filter';
        button.classList.toggle('is-active', role === name);
        button.setAttribute('aria-pressed', role === name ? 'true' : 'false');
        button.textContent = (ROLE_NAMES[name] || name) + ' ' + counts[name];
        button.addEventListener('click', function () {
          role = name;
          renderRoles();
          renderFiles();
        });
        el.roles.appendChild(button);
      });
    }

    function commandsFor(file) {
      return {
        wget: 'wget -c "' + file.url + '"',
        curl: 'curl -L -O "' + file.url + '"',
        url: file.url
      };
    }

    function showCommands(file) {
      commands = commandsFor(file);
      el.guideFile.textContent = file.name;
      document.getElementById('download-command-wget').textContent = commands.wget;
      document.getElementById('download-command-curl').textContent = commands.curl;
      document.getElementById('download-command-url').textContent = commands.url;
      el.guide.hidden = false;
      el.guide.scrollIntoView({ behavior: 'smooth', block: 'nearest' });
    }

    function renderFiles() {
      var files = assembly.files.filter(function (file) {
        return (role === 'all' || file.role === role) &&
          (!el.recommended.checked || file.recommended);
      });

      el.files.innerHTML = '';
      files.forEach(function (file) {
        var row = document.createElement('article');
        row.className = 'finder-file-row';

        var icon = document.createElement('span');
        icon.className = 'finder-file-icon';
        icon.textContent = ROLE_ABBR[file.role] || 'FILE';

        var body = document.createElement('div');
        body.className = 'finder-file-copy';

        var heading = document.createElement('div');
        heading.className = 'finder-file-heading';
        var label = document.createElement('strong');
        label.textContent = file.label;
        heading.appendChild(label);
        if (file.recommended) {
          var badge = document.createElement('span');
          badge.className = 'finder-file-badge';
          badge.textContent = 'Recommended';
          heading.appendChild(badge);
        }

        var filename = document.createElement('code');
        filename.textContent = file.name;
        var meta = document.createElement('small');
        meta.textContent = file.size + ' · updated ' + file.modified;

        body.appendChild(heading);
        body.appendChild(filename);
        body.appendChild(meta);

        var actions = document.createElement('div');
        actions.className = 'finder-file-actions';
        var download = document.createElement('a');
        download.href = file.url;
        download.textContent = 'Download';
        download.setAttribute('download', '');
        var command = document.createElement('button');
        command.type = 'button';
        command.textContent = 'Commands';
        command.addEventListener('click', function () { showCommands(file); });
        actions.appendChild(download);
        actions.appendChild(command);

        row.appendChild(icon);
        row.appendChild(body);
        row.appendChild(actions);
        el.files.appendChild(row);
      });

      if (!files.length) {
        var empty = document.createElement('div');
        empty.className = 'finder-file-empty';
        var strong = document.createElement('strong');
        strong.textContent = 'No files match these filters.';
        var hint = document.createElement('span');
        hint.textContent = 'Clear "Recommended files only" to see index, checksum, and specialized files.';
        empty.appendChild(strong);
        empty.appendChild(hint);
        el.files.appendChild(empty);
      }

      el.summary.textContent = 'Showing ' + files.length + ' of ' +
        assembly.files.length + ' files in this release.';
    }

    function selectAssembly(entry) {
      assembly = entry;
      role = 'all';
      el.recommended.checked = true;
      el.guide.hidden = true;
      el.name.textContent = entry.name;
      el.meta.textContent = entry.species + ' · ' + entry.status + ' release · ' +
        entry.project + ' · version ' + entry.version + ' · ' + entry.id;
      el.directory.href = entry.url;
      renderAssemblies();
      renderRoles();
      renderFiles();
    }

    el.search.addEventListener('input', renderAssemblies);
    el.search.addEventListener('keydown', function (event) {
      if (event.key === 'Escape') {
        el.search.value = '';
        renderAssemblies();
      }
    });
    el.clear.addEventListener('click', function () {
      el.search.value = '';
      renderAssemblies();
      el.search.focus();
    });
    el.recommended.addEventListener('change', renderFiles);
    el.guideClose.addEventListener('click', function () { el.guide.hidden = true; });
    el.guide.addEventListener('click', function (event) {
      var button = event.target.closest('[data-copy-command]');
      if (button && commands) {
        copyValue(commands[button.getAttribute('data-copy-command')], button);
      }
    });

    /* One wget line per biological file type, in the order people usually
       want them. Skips roles the release does not carry. */
    el.copyCore.addEventListener('click', function () {
      var wanted = ['assembly', 'gene_annotation', 'protein', 'cds', 'transcript'];
      var seen = {};
      var lines = [];
      assembly.files.forEach(function (file) {
        if (file.recommended && wanted.indexOf(file.role) !== -1 && !seen[file.role]) {
          lines.push(commandsFor(file).wget);
          seen[file.role] = true;
        }
      });
      copyValue(lines.join('\n'), el.copyCore);
    });

    fetch(root.getAttribute('data-manifest-url'), { credentials: 'same-origin' })
      .then(function (response) {
        if (!response.ok) throw new Error('Catalog request failed');
        return response.json();
      })
      .then(function (data) {
        catalog = data;
        document.getElementById('download-manifest-assemblies').textContent =
          Number(data.assembly_count || 0).toLocaleString('en-US');
        document.getElementById('download-manifest-files').textContent =
          Number(data.file_count || 0).toLocaleString('en-US');
        var generated = new Date(data.generated_at);
        document.getElementById('download-manifest-updated').textContent =
          isNaN(generated.getTime()) ? 'Unknown'
            : generated.toLocaleDateString('en-US', { year: 'numeric', month: 'short', day: 'numeric' });

        el.loading.hidden = true;
        el.app.hidden = false;

        var preferred = data.assemblies.filter(function (entry) {
          return entry.id === 'Zm-B73-REFERENCE-NAM-5.0';
        })[0];
        selectAssembly(preferred || data.assemblies[0]);
      })
      .catch(function () {
        el.loading.hidden = true;
        el.error.hidden = false;
      });
  }

  function initScrollSpy() {
    var tabs = document.querySelectorAll('.mgdb-section-tabs a');
    if (!tabs.length || !('IntersectionObserver' in window)) return;

    var sectionIds = [];
    tabs.forEach(function (tab) {
      var href = tab.getAttribute('href');
      if (href && href.charAt(0) === '#') {
        sectionIds.push(href.substring(1));
      }
    });

    var sections = sectionIds.map(function (id) {
      return document.getElementById(id);
    }).filter(Boolean);

    if (!sections.length) return;

    var observer = new IntersectionObserver(function (entries) {
      entries.forEach(function (entry) {
        if (entry.isIntersecting) {
          var id = entry.target.id;
          tabs.forEach(function (tab) {
            if (tab.getAttribute('href') === '#' + id) {
              tab.classList.add('is-current');
              tab.setAttribute('aria-current', 'true');
            } else {
              tab.classList.remove('is-current');
              tab.removeAttribute('aria-current');
            }
          });
        }
      });
    }, {
      rootMargin: '-10% 0px -75% 0px',
      threshold: 0
    });

    sections.forEach(function (sec) {
      observer.observe(sec);
    });
  }

  // Global clipboard copy helper
  window.copyText = function (elementId, btn) {
    var el = document.getElementById(elementId);
    if (!el) return;
    var text = el.textContent || el.innerText;
    navigator.clipboard.writeText(text.trim()).then(function () {
      var oldText = btn.textContent;
      btn.textContent = 'Copied!';
      setTimeout(function () {
        btn.textContent = oldText;
      }, 2000);
    }).catch(function (err) {
      console.error('Failed to copy: ', err);
    });
  };

  window.copySnippet = function (codeId, btn) {
    var el = document.getElementById(codeId);
    if (!el) return;
    var text = el.textContent || el.innerText;
    navigator.clipboard.writeText(text.trim()).then(function () {
      var oldText = btn.textContent;
      btn.textContent = 'Copied!';
      setTimeout(function () {
        btn.textContent = oldText;
      }, 2000);
    }).catch(function (err) {
      console.error('Failed to copy code snippet: ', err);
    });
  };

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', init);
  } else {
    init();
  }
})();
