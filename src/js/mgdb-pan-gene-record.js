      ['Exemplar', overview.exemplar ? '<span class="mgdb-sequence">' + R.escape(overview.exemplar) + '</span>' : ''],
      ['Members', overview.member_count == null ? '' : R.number(overview.member_count)],
      ['Assemblies represented', overview.assembly_count == null ? '' : R.number(overview.assembly_count)]
